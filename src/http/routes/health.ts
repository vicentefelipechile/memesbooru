// =========================================================================================================
// HEALTH ROUTES (v2)
// =========================================================================================================
// Liveness probe — no auth, no service. Direct DB ping if available.
// =========================================================================================================

// =========================================================================================================
// Imports
// =========================================================================================================

import { Hono } from 'hono';

// =========================================================================================================
// Endpoints
// =========================================================================================================

const router = new Hono<{ Bindings: Env }>();

// =========================================================================================================
// GET /api/health
// Returns status, version and DB connectivity.
// =========================================================================================================

router.get('/', async (c) => {
	let dbStatus: 'ok' | 'error' = 'error';
	try {
		await c.env.DB.prepare('SELECT 1 as v').first();
		dbStatus = 'ok';
	} catch {
		dbStatus = 'error';
	}
	return c.json({ status: 'ok', version: '0.1.0', db: dbStatus });
});

// =========================================================================================================
// Export
// =========================================================================================================

export default router;
